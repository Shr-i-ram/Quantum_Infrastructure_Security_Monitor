def export_scenario_registry(scenarios: list[Scenario], output_dir: pathlib.Path) -> dict[str, pathlib.Path]:
    """Export machine-readable scenario registry and parameter records."""
    reg_dir = output_dir / "scenario_registry"
    reg_dir.mkdir(parents=True, exist_ok=True)

    records = []
    param_records = []

    for sc in scenarios:
        # Determine attack info from config
        atk_cfg = sc.config.attack
        is_attack = bool(atk_cfg and atk_cfg.enabled and atk_cfg.scenarios)
        atk_type = atk_cfg.type if is_attack else "none"
        atk_sev = atk_cfg.scenarios[0].severity if (is_attack and atk_cfg.scenarios) else 0.0

        records.append({
            "scenario_id": sc.scenario_id,
            "infrastructure_id": sc.infrastructure_id,
            "dataset_split": sc.dataset_split,
            "seed": sc.seed,
            "regime": sc.regime,
            "is_edge_case": sc.is_edge_case,
            "config_hash": sc.config_hash,
            "pulses_per_run": sc.config.protocol.n_pulses,
            "attack_enabled": is_attack,
            "attack_type": atk_type,
            "attack_severity": atk_sev,
        })

        p_row = {"scenario_id": sc.scenario_id, "dataset_split": sc.dataset_split}
        for k, v in sc.sampled_parameters.items():
            if isinstance(v, (int, float, str, bool)):
                p_row[k] = v
        param_records.append(p_row)

    df_reg = pd.DataFrame(records)
    df_params = pd.DataFrame(param_records)

    reg_parquet = reg_dir / "scenario_registry.parquet"
    reg_csv = reg_dir / "scenario_registry.csv"
    param_parquet = reg_dir / "scenario_parameters.parquet"
    param_csv = reg_dir / "scenario_parameters.csv"

    df_reg.to_parquet(reg_parquet, index=False)
    df_reg.to_csv(reg_csv, index=False)
    df_params.to_parquet(param_parquet, index=False)
    df_params.to_csv(param_csv, index=False)

    return {
        "scenario_registry_parquet": reg_parquet,
        "scenario_registry_csv": reg_csv,
        "scenario_parameters_parquet": param_parquet,
        "scenario_parameters_csv": param_csv,
    }
