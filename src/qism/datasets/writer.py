"""Dataset writer: chunked Parquet persistence with atomic writes.

On-disk layout of a run directory::

    <run_dir>/
        chunks/events_%06d.parquet      # one per simulated chunk (transient)
        chunks/telemetry_%06d.parquet   # one per completed window (transient)
        events.parquet                  # combined events (written at finalize)
        telemetry.parquet               # combined telemetry (written at finalize)
        manifest.json                   # provenance (atomic)
        config.yaml                     # effective configuration (atomic)
        README.md                       # dataset summary

Chunk files are written atomically (tmp + fsync + rename). Combined files are
streamed with a ParquetWriter (no giant in-memory DataFrames). After a
successful finalize the transient chunk directory is removed.
"""

from __future__ import annotations

import logging
import os
import pathlib
from typing import Any

import numpy as np
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq

from qism.telemetry.events import EVENT_SCHEMA

log = logging.getLogger("qism.writer")

_README_TEMPLATE = """# QISM run dataset: {run_id}

Generated by the Quantum Infrastructure Security Monitor simulator v{simulator_version}.

Files:
  events.parquet      event-level telemetry (one row per pulse)
  telemetry.parquet   window-level physics-informed features
  manifest.json       provenance (seeds, versions, configuration hash, status)
  config.yaml         the exact effective configuration of this run

See the project README for the full schema documentation.
"""


def _fsync_file(path: pathlib.Path) -> None:
    # Windows requires the handle opened for writing before fsync is allowed.
    with open(path, "r+b") as fh:
        os.fsync(fh.fileno())


def _atomic_write_table(table: pa.Table, path: pathlib.Path) -> None:
    """Write a pyarrow table atomically (tmp + fsync + rename)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    pq.write_table(table, tmp)
    _fsync_file(tmp)
    os.replace(tmp, path)


def _stream_concat(chunk_files: list[pathlib.Path], out_path: pathlib.Path) -> int:
    """Concatenate chunk parquet files into one streamed parquet file."""
    if not chunk_files:
        return 0

    tables = [pq.read_table(f) for f in chunk_files]
    try:
        combined = pa.concat_tables(tables, promote_options="default")
    except Exception:
        # Fallback if promote_options is not supported
        combined = pa.concat_tables(tables)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(combined, out_path)
    return combined.num_rows


class DatasetWriter:
    """Writes one run's dataset directory."""

    def __init__(self, run_dir: pathlib.Path):
        self.run_dir = pathlib.Path(run_dir)
        self.chunks_dir = self.run_dir / "chunks"

    # ------------------------------------------------------------------ #
    # Chunk-level writes
    # ------------------------------------------------------------------ #
    def write_events_chunk(self, events: pd.DataFrame, chunk_index: int) -> pathlib.Path:
        path = self.chunks_dir / f"events_{chunk_index:06d}.parquet"
        table = pa.Table.from_pandas(events, preserve_index=False)
        _atomic_write_table(table, path)
        return path

    def write_telemetry_chunk(self, row_df: pd.DataFrame, window_id: int) -> pathlib.Path:
        path = self.chunks_dir / f"telemetry_{window_id:06d}.parquet"
        table = pa.Table.from_pandas(row_df, preserve_index=False)
        _atomic_write_table(table, path)
        return path

    def event_chunk_files(self) -> list[pathlib.Path]:
        if not self.chunks_dir.exists():
            return []
        return sorted(self.chunks_dir.glob("events_*.parquet"))

    def telemetry_chunk_files(self) -> list[pathlib.Path]:
        if not self.chunks_dir.exists():
            return []
        return sorted(self.chunks_dir.glob("telemetry_*.parquet"))

    def clear_telemetry_chunks(self) -> None:
        for f in self.telemetry_chunk_files():
            f.unlink(missing_ok=True)

    def chunk_index_of(self, path: pathlib.Path) -> int:
        return int(path.stem.rsplit("_", 1)[1])

    def chunk_rows(self, path: pathlib.Path) -> int:
        return pq.read_metadata(path).num_rows

    def read_events_chunk(self, path: pathlib.Path) -> pd.DataFrame:
        return pq.read_table(path).to_pandas()

    # ------------------------------------------------------------------ #
    # Run-level files
    # ------------------------------------------------------------------ #
    def write_config(self, config) -> None:
        from qism.config import save_config

        save_config(config, self.run_dir / "config.yaml")

    def write_manifest(self, manifest: dict[str, Any]) -> None:
        from qism.datasets.manifest import write_manifest_atomic

        write_manifest_atomic(manifest, self.run_dir / "manifest.json")

    def write_readme(self, simulator_version: str) -> None:
        (self.run_dir / "README.md").write_text(
            _README_TEMPLATE.format(run_id=self.run_dir.name, simulator_version=simulator_version),
            encoding="utf-8",
        )

    def final_events_path(self) -> pathlib.Path:
        return self.run_dir / "events.parquet"

    def final_telemetry_path(self) -> pathlib.Path:
        return self.run_dir / "telemetry.parquet"

    def final_events_exists(self) -> bool:
        return self.final_events_path().exists()

    def read_final_telemetry(self) -> pd.DataFrame | None:
        p = self.final_telemetry_path()
        if not p.exists():
            return None
        return pq.read_table(p).to_pandas()

    def read_final_events(self) -> pd.DataFrame | None:
        p = self.final_events_path()
        if not p.exists():
            return None
        return pq.read_table(p).to_pandas()

    # ------------------------------------------------------------------ #
    # Finalize + quality checks
    # ------------------------------------------------------------------ #
    def finalize(
        self,
        *,
        expected_pulses: int,
        config_hash: str,
        simulator_version: str,
        window_size: int,
    ) -> list[str]:
        """Combine chunk files, run data-quality checks, clean up chunks.

        Returns a list of issues; an empty list means the dataset is valid.
        The caller must NOT mark the dataset COMPLETED when issues exist.
        """
        event_files = self.event_chunk_files()
        telemetry_files = self.telemetry_chunk_files()
        if not event_files:
            return ["no event chunk files found — dataset is empty"]

        n_events = _stream_concat(event_files, self.final_events_path())
        n_telemetry = _stream_concat(telemetry_files, self.final_telemetry_path())

        events = pq.read_table(self.final_events_path()).to_pandas()
        telemetry = pq.read_table(self.final_telemetry_path()).to_pandas()

        issues = self.quality_checks(events, telemetry, expected_pulses, n_events, window_size)

        # manifest reconciliation
        manifest_path = self.run_dir / "manifest.json"
        if manifest_path.exists():
            from qism.datasets.manifest import update_manifest_field

            update_manifest_field(
                manifest_path,
                pulses_completed=n_events,
                status="FAILED" if issues else "COMPLETED",
                files={
                    "events.parquet": n_events,
                    "telemetry.parquet": n_telemetry,
                },
            )
        self.write_readme(simulator_version)

        # The chunk files are intentionally retained: they are the authoritative
        # cursor for checkpoint recovery and allow a completed run to be
        # *extended* (resumed with a larger pulse count) without regenerating
        # already-committed events. They duplicate the combined files on disk;
        # delete ``chunks/`` manually if space matters and extension is not needed.
        return issues

    def quality_checks(
        self,
        events: pd.DataFrame,
        telemetry: pd.DataFrame,
        expected_pulses: int,
        n_events: int,
        window_size: int,
    ) -> list[str]:
        """Data-quality checks (QISM spec §51). Returns a list of issues."""
        issues: list[str] = []
        valid_intensity = {"signal", "decoy", "vacuum"}
        from qism.types import ClickType

        valid_click_types = {member.value for member in ClickType}

        if len(events) != expected_pulses:
            issues.append(f"expected {expected_pulses} event rows, found {len(events)}")
        if n_events != expected_pulses:
            issues.append(f"combined events file has {n_events} rows != expected {expected_pulses}")

        pulse = events["pulse_id"].to_numpy()
        if len(pulse) and not (pulse[0] == 0 and np.all(np.diff(pulse) == 1)):
            issues.append("pulse_ids are not contiguous from 0")
        if len(pulse) and len(np.unique(pulse)) != len(pulse):
            issues.append("duplicate pulse_ids found")

        for col in ("alice_bit", "alice_basis", "bob_basis"):
            vals = events[col].dropna()
            if not vals.isin([0, 1]).all():
                issues.append(f"{col} contains values outside {{0, 1}}")

        if not events["intensity_class"].isin(valid_intensity).all():
            issues.append("intensity_class contains invalid values")
        if not events["click_type"].isin(valid_click_types).all():
            issues.append("click_type contains invalid values")

        for col in ("mu", "channel_transmittance", "polarization_misalignment"):
            if events[col].isna().any():
                issues.append(f"{col} contains NaN (never expected)")
        if (events["mu"] < 0).any():
            issues.append("mu < 0 found")
        if ((events["channel_transmittance"] <= 0) | (events["channel_transmittance"] > 1)).any():
            issues.append("channel_transmittance outside (0, 1]")
        if (
            (events["polarization_misalignment"] < 0) | (events["polarization_misalignment"] > 1)
        ).any():
            issues.append("polarization_misalignment outside [0, 1]")
        if (events["photon_number"] < 0).any():
            issues.append("negative photon_number found")

        # NaN is allowed only where mathematically undefined (no click events)
        # or in FUTURE_ONLY fields that are null by design in V0.1.
        nan_allowed = {
            "arrival_time_s",
            "timing_offset_s",
            "detector_id",
            "bit_error",
            "detector_efficiency",
            "dark_count_rate",
            # V0.2: per-detector arrival/dead/afterpulse fields are NaN when
            # the detector did not click / no afterpulse was attempted.
            "detector_0_arrival_time_s",
            "detector_1_arrival_time_s",
            "detector_0_time_since_last_click_s",
            "detector_1_time_since_last_click_s",
            "detector_0_dead_duration_s",
            "detector_1_dead_duration_s",
            "afterpulse_parent_pulse_id",
            "afterpulse_delay_s",
            # V0.4: environmental sensor readings and ground truth (may be NaN
            # during sensor missingness or unmonitored stable-baseline operation)
            "sensor_temperature_c",
            "sensor_humidity_pct",
            "sensor_vibration_g",
            "sensor_background_light_lux",
            "true_temperature_c",
            "true_humidity_pct",
            "true_vibration_g",
            "true_channel_loss_db",
            "true_polarization_drift_deg",
        }
        from qism.types import FieldCategory

        nan_allowed |= {
            name
            for name, spec in EVENT_SCHEMA.items()
            if spec.category is FieldCategory.FUTURE_ONLY
        }
        for col in events.columns:
            if col in nan_allowed or col in ("run_id", "scenario_id"):
                continue
            if events[col].isna().any():
                issues.append(f"{col} contains NaN but is a non-nullable field")

        ts = events["timestamp"].to_numpy()
        if len(ts) and not np.all(np.diff(ts) > 0):
            issues.append("timestamps are not strictly increasing")

        # window bookkeeping
        if (
            len(events)
            and not (
                events["window_id"].to_numpy() == events["pulse_id"].to_numpy() // window_size
            ).all()
        ):
            issues.append("window_id does not equal pulse_id // window_size")

        if len(telemetry):
            wids = telemetry["window_id"].to_numpy()
            if not (np.diff(wids) == 1).all() or wids[0] != 0:
                issues.append("telemetry window_ids are not contiguous from 0")
            if telemetry["run_id"].nunique() != 1:
                issues.append("telemetry contains multiple run_ids")
            if (telemetry["n_pulses"] <= 0).any():
                issues.append("telemetry contains windows with n_pulses <= 0")

        if issues:
            log.error(
                "data-quality checks failed for %s:\n  - %s", self.run_dir, "\n  - ".join(issues)
            )
        else:
            log.info(
                "data-quality checks passed for %s (%d events, %d windows)",
                self.run_dir,
                len(events),
                len(telemetry),
            )
        return issues
